CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY,data TEXT);
CREATE TABLE IF NOT EXISTS incidents(id TEXT PRIMARY KEY,status TEXT,data TEXT);
CREATE TABLE IF NOT EXISTS audit(id INTEGER PRIMARY KEY,ts TEXT,user TEXT,action TEXT,inc TEXT,prev TEXT,new TEXT,descr TEXT);
CREATE TABLE IF NOT EXISTS config(k TEXT PRIMARY KEY,data TEXT);
CREATE TABLE IF NOT EXISTS notifications(user TEXT,ts TEXT,msg TEXT);
CREATE TABLE IF NOT EXISTS notification_seen(user TEXT PRIMARY KEY,last_id INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sequences(name TEXT PRIMARY KEY,value INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit_visibility(event_id INTEGER PRIMARY KEY, hidden INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit_links(event_id INTEGER PRIMARY KEY, target INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS attachments(id TEXT PRIMARY KEY, incident TEXT NOT NULL, data TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS attachments_incident ON attachments(incident);
CREATE TABLE IF NOT EXISTS email_queue(id INTEGER PRIMARY KEY, recipient TEXT, subject TEXT, body TEXT,
    incident TEXT, event TEXT, attempts INTEGER DEFAULT 0, next REAL DEFAULT 0, status TEXT DEFAULT 'pending', error TEXT);
